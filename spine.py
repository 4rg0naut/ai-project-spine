TPL["AGENTS.md"] = """# %NAME% - agent start-here

One-sentence purpose: see STATE.md first line block. Generated by
ai-project-spine %VER% on %DATE%.

Boot ritual (every session, in order):
1. Read STATE.md - it is the state and ends with the literal next command.
2. Run: python3 tools/spine.py verify   (gate; must exit 0 before work)
3. TODO.md entries are stale hypotheses until re-justified in your own
   words against gates + DECISIONS.md. Deleting one is a valid first act.

Rules live where they already live - do not restate them here:
- decisions/contracts: DECISIONS.md   - open risks: BUGS.md
- intentions + decay mechanics: TODO.md header
- lessons: LESSONS/
- rule citations with dates: claims/claims.jsonl (spine.rule events)

Editing: any tool may edit prose, then run
  python3 tools/spine.py sign <files> --by WHO --reason "why"
This file stays short: no file-path inventories, no duplicated rules.
If a line here duplicates another file, delete it here.
"""

