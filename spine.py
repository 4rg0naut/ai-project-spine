#!/usr/bin/env python3
"""ai-project-spine v0.1 - download, execute, get a rule-bearing skeleton.

One stdlib-only file. `init` generates a project skeleton whose rules are
ledger-backed: every design choice is an event in claims/claims.jsonl with
its citation and date, every generated file is hash-attested. Afterward
`verify` screams if any spine file changed outside the gate; `sign` is the
retroactive attestation for authorized hand edits.

Commands:
  init  --name NAME [--dir DIR] [--force]   generate skeleton here
  verify                                    gate: chain + attestations + rules
  sign  [FILES...] --by WHO --reason TEXT   attest current hashes
  ledger                                    print ledger events

v0.1 scope is init/verify/sign. `loop` (confidence decay) and `mcp` are v0.2,
tracked in this repo's README - deliberately not built yet (rule R5 below).
"""
import argparse
import hashlib
import json
import os
import shutil
import sys
import time

VERSION = "0.1.0"
LEDGER = os.path.join("claims", "claims.jsonl")

# Rule claims: the generator's own design rationale, dated and cited.
# Written into every generated ledger so the project inherits its "why".
RULES = [
    ("R1-hub-pointer", "Skeleton uses one small AGENTS.md pointing at files "
     "that already hold the rules; hub+pointer is the dominant cross-tool "
     "pattern (CLAUDE.md->AGENTS.md the most frequent reference pair).",
     "https://arxiv.org/abs/2602.14690", "2026-02-16"),
    ("R2-small-context", "AGENTS.md capped at N lines: context files cut "
     "runtime/tokens when small (controlled study) and bloat past an "
     "~150-200 instruction budget makes rules get ignored, not obeyed.",
     "https://arxiv.org/abs/2601.20404 ; "
     "https://www.humanlayer.dev/blog/writing-a-good-claude-md", "2026-02"),
    ("R3-staleness-gate", "Documented paths and lists go stale and stale "
     "context poisons agents that re-read it every request; therefore verify "
     "enforces size and pointer integrity instead of trusting prose.",
     "https://www.aihero.dev/a-complete-guide-to-agents-md ; "
     "https://addyo.substack.com/p/audit-your-agent-files", "2026-01/08"),
    ("R4-plan-not-order", "TODO entries are hypotheses with confidence that "
     "decays when untouched; escalation-of-commitment in LLMs is "
     "context-dependent and prior-investment framing triggers it, so past "
     "plans must sink without fresh evidence. Writing planned steps down "
     "discharges intrusive open-loop load (human-side benefit).",
     "https://arxiv.org/abs/2508.01545 ; "
     "https://pubmed.ncbi.nlm.nih.gov/21688924/", "2025-08 / 2011"),
    ("R5-small-surface", "v0.1 ships init+verify+sign only; advanced "
     "mechanisms (skills, subagents, hooks) see shallow real-world adoption, "
     "so executable depth is added only after a customer earns it.",
     "https://arxiv.org/abs/2602.14690", "2026-02-16"),
    ("R6-attest-not-forbid", "Writes outside the gate are legal but must be "
     "signed with actor+reason; hash-chained ledger makes unsigned drift "
     "visible, which is the actual defense (obfuscation adds nothing a "
     "motivated writer cannot undo).",
     "OpenClaims v0.1 event model (fleet: Memory_Knowledge/vendor/openclaims)",
     "2026-10"),
]

PARAMS = {"agents_md_max_lines": 25, "todo_max_items": 3}


def sha(b):
    if isinstance(b, str):
        b = b.encode("utf-8")
    return hashlib.sha256(b).hexdigest()


def canonical(ev):
    return json.dumps(ev, sort_keys=True, separators=(",", ":"))


def last_digest(path):
    d = "GENESIS"
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    d = json.loads(line)["digest"]
    return d


def append_event(root, etype, payload):
    path = os.path.join(root, LEDGER)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    prev = last_digest(path)
    ev = {"event_id": "ev_" + sha((prev + etype + str(time.time()))[:64])[:20],
          "prev": prev, "type": etype, "payload": payload}
    ev["digest"] = sha(prev + canonical(ev))
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(ev, sort_keys=True) + "\n")
    return ev


def read_events(root):
    out = []
    path = os.path.join(root, LEDGER)
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


# ---------------------------------------------------------------- templates
