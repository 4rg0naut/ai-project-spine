FILES = ["AGENTS.md", "STATE.md", "TODO.md", "DECISIONS.md", "BUGS.md",
         "CLAIMS.md", "LESSONS/README.md", "tests/run.sh", ".gitignore"]


def render(tpl, name):
    return (tpl.replace("%NAME%", name).replace("%VER%", VERSION)
            .replace("%DATE%", time.strftime("%Y-%m-%d"))
            .replace("%TODO_MAX%", str(PARAMS["todo_max_items"])))


# ---------------------------------------------------------------- commands
def cmd_init(args):
    root = args.dir
    if os.path.exists(os.path.join(root, LEDGER)) and not args.force:
        sys.exit("spine: ledger already exists in %s (use --force)" % root)
    for rel in FILES:
        dest = os.path.join(root, rel)
        if os.path.exists(dest) and not args.force:
            sys.exit("spine: refuses to overwrite %s (use --force)" % rel)
        os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
        with open(dest, "w", encoding="utf-8") as fh:
            fh.write(render(TPL[rel], args.name))
    os.chmod(os.path.join(root, "tests", "run.sh"), 0o755)
    os.makedirs(os.path.join(root, "tools"), exist_ok=True)
    shutil.copy2(os.path.abspath(__file__), os.path.join(root, "tools",
                                                         "spine.py"))
    for rid, text, src, asof in RULES:
        append_event(root, "spine.rule", {"id": rid, "text": text,
                                          "source": src, "true_asof": asof})
    for rel in FILES + ["tools/spine.py"]:
        with open(os.path.join(root, rel), "rb") as fh:
            append_event(root, "spine.attest", {"path": rel,
                                                "sha256": sha(fh.read()),
                                                "by": "spine " + VERSION,
                                                "reason": "init"})
    print("spine: skeleton ready in %s (%d files attested, %d rules seeded)"
          % (root, len(FILES) + 1, len(RULES)))
    print("spine: next ->  python3 tools/spine.py verify   then read AGENTS.md")


def cmd_verify(args):
    root = args.dir
    events = read_events(root)
    if not events:
        sys.exit("verify: no ledger at %s - run init first" % root)
    fails = []
    prev = "GENESIS"
    for ev in events:
        body = {k: v for k, v in ev.items() if k != "digest"}
        if ev["prev"] != prev or sha(prev + canonical(body)) != ev["digest"]:
            fails.append("CHAIN broken at %s" % ev["event_id"])
            break
        prev = ev["digest"]
    att = {}
    for ev in events:
        if ev["type"] == "spine.attest":
            att[ev["payload"]["path"]] = ev["payload"]["sha256"]
    for rel, h in sorted(att.items()):
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            fails.append("MISSING attested file: %s" % rel)
            continue
        with open(p, "rb") as fh:
            if sha(fh.read()) != h:
                fails.append("UNATTESTED: %s modified outside the gate" % rel)
    tracked = set(att)
    for rel in FILES:
        if rel not in tracked and os.path.exists(os.path.join(root, rel)):
            fails.append("UNTRACKED spine file: %s (never attested)" % rel)
    ag = os.path.join(root, "AGENTS.md")
    if os.path.exists(ag):
        n = len(open(ag, encoding="utf-8").read().splitlines())
        if n > PARAMS["agents_md_max_lines"]:
            fails.append("AGENTS.md %d lines > cap %d (rule R2/R3)"
                         % (n, PARAMS["agents_md_max_lines"]))
    st = os.path.join(root, "STATE.md")
    if os.path.exists(st):
        if "Next command:" not in open(st, encoding="utf-8").read():
            fails.append("STATE.md lost its literal next-command (resume "
                         "rule broken)")
    for f in fails:
        print("FAIL:", f)
    if fails:
        print("VERIFY: FAIL (%d)" % len(fails))
        sys.exit(1)
    print("VERIFY: PASS (%d events, %d files attested)"
          % (len(events), len(att)))


def cmd_sign(args):
    root = args.dir
    if not args.files:
        att = {}
        for ev in read_events(root):
            if ev["type"] == "spine.attest":
                att[ev["payload"]["path"]] = ev["payload"]["sha256"]
        todo = []
        for rel, h in sorted(att.items()):
            p = os.path.join(root, rel)
            if os.path.exists(p):
                with open(p, "rb") as fh:
                    if sha(fh.read()) != h:
                        todo.append(rel)
        args.files = todo
    if not args.files:
        print("sign: nothing drifted")
        return
    for rel in args.files:
        p = os.path.join(root, rel)
        with open(p, "rb") as fh:
            append_event(root, "spine.attest",
                         {"path": rel, "sha256": sha(fh.read()),
                          "by": args.by, "reason": args.reason,
                          "signed_at": time.strftime("%Y-%m-%dT%H:%M:%S")})
        print("signed:", rel)


def cmd_ledger(args):
    for ev in read_events(args.dir):
        p = ev["payload"]
        print(ev["type"], p.get("id") or p.get("path") or "",
              (p.get("text") or p.get("by") or "")[:70])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd")
    pi = sub.add_parser("init")
    pi.add_argument("--name", required=True)
    pi.add_argument("--dir", default=".")
    pi.add_argument("--force", action="store_true")
    pv = sub.add_parser("verify")
    pv.add_argument("--dir", default=".")
    ps = sub.add_parser("sign")
    ps.add_argument("files", nargs="*")
    ps.add_argument("--by", required=True)
    ps.add_argument("--reason", required=True)
    ps.add_argument("--dir", default=".")
    pl = sub.add_parser("ledger")
    pl.add_argument("--dir", default=".")
    args = ap.parse_args()
    if not args.cmd:
        ap.print_help()
        sys.exit(2)
    {"init": cmd_init, "verify": cmd_verify, "sign": cmd_sign,
     "ledger": cmd_ledger}[args.cmd](args)


if __name__ == "__main__":
    main()
