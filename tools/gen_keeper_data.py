#!/usr/bin/env python3
"""Generate keeper/src/generated.rs from spine.py's own constants.

Criterion 21: the Rust keeper must land byte-identical skeleton files.
Retyping templates is how drift is born, so the generator imports the
Python spine and re-emits VERSION/PARAMS/FILES/RULES/TPL as Rust values,
serialized through the SAME canonical dump path both sides use (dump ==
json.dumps(sort_keys=True), itself proven by the difftest). Run this
after any spine.py template change:

    python3 tools/gen_keeper_data.py && (cd keeper && cargo test)

Integrity gate: `spine.py index digest` and `keeper hash-templates` must
agree on one sha256 over this exact spec; the difftest fails otherwise.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)
import spine  # noqa: E402


def rust_j(v):
    if v is None:
        return "J::Nul"
    if isinstance(v, bool):
        return "J::Bool(%s)" % ("true" if v else "false")
    if isinstance(v, int):
        return "J::Int(%d)" % v
    if isinstance(v, float):
        return "J::Num(%r)" % v
    if isinstance(v, str):
        return "J::Str(%s.to_string())" % json.dumps(v)
    if isinstance(v, (list, tuple)):
        return "J::Arr(vec![%s])" % ", ".join(rust_j(x) for x in v)
    if isinstance(v, dict):
        inner = ", ".join("(%s.to_string(), %s)" % (json.dumps(k), rust_j(x))
                          for k, x in v.items())
        return "J::Obj(vec![%s])" % inner
    raise TypeError(type(v))


def main():
    spec = {
        "version": spine.VERSION,
        "params": dict(sorted(spine.PARAMS.items())),
        "files": list(spine.FILES),
        "new_in_v05": list(spine.NEW_IN_V05),
        "rules": [[r[0], r[1], r[2], r[3]] for r in spine.RULES],
        "tpl": {k: spine.TPL[k] for k in sorted(spine.TPL)},
    }
    blob = json.dumps(spec, sort_keys=True)
    digest = spine.hashlib.sha256(blob.encode()).hexdigest()
    out = [
        "// GENERATED by tools/gen_keeper_data.py - do not edit by hand.",
        "// Source of truth: spine.py constants. Digest below must equal",
        "// `python3 spine.py index digest` output (difftest enforces it).",
        "// Digest: %s" % digest,
        "",
        "use super::J;",
        "",
        "pub fn spec() -> J {",
        "    %s" % rust_j(spec),
        "}",
    ]
    dest = os.path.join(REPO, "keeper", "src", "generated.rs")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote keeper/src/generated.rs (%d bytes, digest %s)"
          % (os.path.getsize(dest), digest))
    check = subprocess.run([sys.executable, os.path.join(REPO, "spine.py"),
                            "index", "digest", "--dir", "."],
                           capture_output=True, text=True)
    want = check.stdout.strip()
    if want != digest:
        print("WARN: spine digest mismatch: spine=%s spec=%s - fix"
              " cmd_index_digest to match this script's spec shape"
              % (want, digest))
        sys.exit(1)


if __name__ == "__main__":
    main()
